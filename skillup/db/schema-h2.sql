-- 게시판 테이블 만들기 (H2). 내 PC H2에서 SCRIPT NODATA로 뽑아 정리(11/05)
-- 이미 있으면 건너뜀(IF NOT EXISTS) — 앱이 켜질 때마다 실행돼도 안전

CREATE TABLE IF NOT EXISTS member (
    member_idx INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    user_id    CHARACTER VARYING(50)  NOT NULL,
    pwd        CHARACTER VARYING(250) NOT NULL,
    name       CHARACTER VARYING(50)  NOT NULL,
    role       ENUM('user', 'admin') DEFAULT 'user' NOT NULL,
    use_yn     ENUM('Y', 'N') DEFAULT 'Y' NOT NULL,
    reg_dttm   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    upt_dttm   TIMESTAMP,
    del_dttm   TIMESTAMP,
    CONSTRAINT member_pk PRIMARY KEY (member_idx),
    CONSTRAINT member_user_id_uk UNIQUE (user_id)
);

CREATE TABLE IF NOT EXISTS board (
    board_idx      INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    title          CHARACTER VARYING(255) NOT NULL,
    content        CHARACTER VARYING(3000),
    member_idx     INTEGER NOT NULL,
    del_yn         ENUM('Y', 'N') DEFAULT 'N' NOT NULL,
    reg_dttm       TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    upt_member_idx INTEGER,
    upt_dttm       TIMESTAMP,
    del_member_idx INTEGER,
    del_dttm       TIMESTAMP,
    CONSTRAINT board_pk PRIMARY KEY (board_idx),
    CONSTRAINT member_fk FOREIGN KEY (member_idx) REFERENCES member (member_idx)
);

CREATE TABLE IF NOT EXISTS board_file (
    file_idx           INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    board_idx          INTEGER NOT NULL,
    file_original_name CHARACTER VARYING(255) NOT NULL,
    file_save_name     CHARACTER VARYING(100) NOT NULL,
    file_size          BIGINT NOT NULL,
    del_yn             ENUM('Y', 'N') DEFAULT 'N' NOT NULL,
    reg_dttm           TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    del_dttm           TIMESTAMP,
    CONSTRAINT board_file_pk PRIMARY KEY (file_idx),
    CONSTRAINT board_file_fk FOREIGN KEY (board_idx) REFERENCES board (board_idx)
);
